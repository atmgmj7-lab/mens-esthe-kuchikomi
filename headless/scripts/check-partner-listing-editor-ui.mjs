import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const api = join(root, "app/api/partner/listing/route.ts");
const page = join(root, "app/partner/listing/page.tsx");
const editor = join(root, "components/partner/PartnerListingEditor.tsx");
const operatorPage = join(root, "app/dashboard/listing-applications/partner-revisions/page.tsx");
const operatorView = join(root, "components/dashboard/PartnerListingRevisions.tsx");
const bannerRoute = join(root, "app/api/partner/listing/banner/route.ts");
const publicListing = join(root, "lib/partner/public-listing.ts");
for (const path of [api, page, editor, operatorPage, operatorView, bannerRoute, publicListing]) assert.ok(existsSync(path), `missing Partner listing editor file: ${path}`);
const apiSource = readFileSync(api, "utf8");
const pageSource = readFileSync(page, "utf8");
const editorSource = readFileSync(editor, "utf8");
const operatorSource = readFileSync(operatorView, "utf8");
const bannerSource = readFileSync(bannerRoute, "utf8");
const publicSource = readFileSync(publicListing, "utf8");
assert.match(apiSource, /authorizePartnerSession/);
assert.match(apiSource, /get_partner_listing_editor/);
assert.match(apiSource, /save_partner_listing_draft/);
assert.match(apiSource, /submit_partner_listing_change/);
assert.doesNotMatch(apiSource, /requestedWorkspaceId:\s*body/);
assert.match(pageSource, /PartnerListingEditor/);
assert.match(editorSource, /差し戻し理由/);
assert.match(editorSource, /下書きを保存/);
assert.match(editorSource, /変更を申請する/);
assert.match(editorSource, /credentials:\s*["']include/);
assert.match(editorSource, /api\/partner\/listing\/banner/);
assert.match(operatorSource, /公開中の紹介文/);
assert.match(operatorSource, /差し戻し/);
assert.match(operatorSource, /partner-listing-revisions/);
assert.match(bannerSource, /authorizePartnerSession/);
assert.match(bannerSource, /inspectListingImage/);
assert.match(bannerSource, /reserve_partner_listing_banner_upload/);
assert.match(bannerSource, /attach_partner_listing_banner_asset/);
assert.match(publicSource, /get_public_listing_store_by_slug/);
console.log("partner listing editor UI contract: PASS");
