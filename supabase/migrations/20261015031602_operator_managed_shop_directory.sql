create or replace function private.assert_managed_shop_payload(
  p_managed_shop_id uuid, p_payload jsonb
) returns void language plpgsql security definer set search_path=private,pg_temp as $$
declare
  v_name text;
  v_area_slug text;
  v_area_name text;
  v_official_url text;
  v_gallery uuid[];
  v_banner uuid;
begin
  if p_payload is null or jsonb_typeof(p_payload) <> 'object'
    or p_payload - array['shop_name','area_slug','area_name','official_url','introduction','address','business_hours','phone','line_url','booking_url','basic_price','price_90','banner_asset_id','gallery_asset_ids'] <> '{}'::jsonb then
    raise exception 'invalid managed shop payload' using errcode='22023';
  end if;
  v_name := nullif(trim(p_payload->>'shop_name'),'');
  v_area_slug := nullif(trim(p_payload->>'area_slug'),'');
  v_area_name := nullif(trim(p_payload->>'area_name'),'');
  v_official_url := nullif(trim(p_payload->>'official_url'),'');
  if char_length(v_name) not between 1 and 120 or v_area_slug !~ '^[^/[:space:]]{1,200}$'
    or char_length(v_area_name) not between 1 and 120 or v_official_url !~ '^https?://'
    or char_length(nullif(trim(coalesce(p_payload->>'introduction','')),'')) > 5000
    or char_length(nullif(trim(coalesce(p_payload->>'address','')),'')) > 500
    or char_length(nullif(trim(coalesce(p_payload->>'business_hours','')),'')) > 500
    or char_length(nullif(trim(coalesce(p_payload->>'phone','')),'')) > 120
    or (nullif(trim(coalesce(p_payload->>'line_url','')),'') is not null and nullif(trim(p_payload->>'line_url'),'') !~ '^https?://')
    or (nullif(trim(coalesce(p_payload->>'booking_url','')),'') is not null and nullif(trim(p_payload->>'booking_url'),'') !~ '^https?://')
    or (p_payload ? 'basic_price' and p_payload->'basic_price' <> 'null'::jsonb and (p_payload->>'basic_price') !~ '^[1-9][0-9]{0,6}$')
    or (p_payload ? 'price_90' and p_payload->'price_90' <> 'null'::jsonb and (p_payload->>'price_90') !~ '^[1-9][0-9]{0,6}$') then
    raise exception 'invalid managed shop payload' using errcode='22023';
  end if;
  begin
    v_banner := nullif(p_payload->>'banner_asset_id','')::uuid;
    select coalesce(array_agg(value::uuid order by ordinality), '{}'::uuid[]) into v_gallery
    from jsonb_array_elements_text(coalesce(p_payload->'gallery_asset_ids','[]'::jsonb)) with ordinality;
  exception when invalid_text_representation then
    raise exception 'invalid managed shop asset id' using errcode='22023';
  end;
  if jsonb_typeof(coalesce(p_payload->'gallery_asset_ids','[]'::jsonb)) <> 'array' or cardinality(v_gallery) > 10
    or cardinality(v_gallery) <> cardinality(array(select distinct unnest(v_gallery))) then
    raise exception 'invalid managed shop gallery' using errcode='22023';
  end if;
  if v_banner is not null and not exists (select 1 from private.managed_shop_assets where id=v_banner and managed_shop_id=p_managed_shop_id) then
    raise exception 'managed shop banner does not belong to store' using errcode='42501';
  end if;
  if exists (select 1 from unnest(v_gallery) as asset_id where not exists (select 1 from private.managed_shop_assets where id=asset_id and managed_shop_id=p_managed_shop_id)) then
    raise exception 'managed shop gallery does not belong to store' using errcode='42501';
  end if;
end;
$$;

create or replace function private.insert_managed_shop_revision(
  p_managed_shop_id uuid, p_revision integer, p_state text, p_payload jsonb
) returns void language plpgsql security definer set search_path=private,pg_temp as $$
begin
  perform private.assert_managed_shop_payload(p_managed_shop_id,p_payload);
  insert into private.managed_shop_revisions(
    managed_shop_id,revision,state,shop_name,area_slug,area_name,official_url,introduction,address,business_hours,phone,line_url,booking_url,basic_price,price_90,banner_asset_id,gallery_asset_ids
  ) values (
    p_managed_shop_id,p_revision,p_state,
    trim(p_payload->>'shop_name'),trim(p_payload->>'area_slug'),trim(p_payload->>'area_name'),trim(p_payload->>'official_url'),
    nullif(trim(coalesce(p_payload->>'introduction','')),''),nullif(trim(coalesce(p_payload->>'address','')),''),
    nullif(trim(coalesce(p_payload->>'business_hours','')),''),nullif(trim(coalesce(p_payload->>'phone','')),''),
    nullif(trim(coalesce(p_payload->>'line_url','')),''),nullif(trim(coalesce(p_payload->>'booking_url','')),''),
    nullif(p_payload->>'basic_price','')::integer,nullif(p_payload->>'price_90','')::integer,
    nullif(p_payload->>'banner_asset_id','')::uuid,
    coalesce(array(select value::uuid from jsonb_array_elements_text(coalesce(p_payload->'gallery_asset_ids','[]'::jsonb))), '{}'::uuid[])
  );
end;
$$;

create or replace function private.import_managed_shop_from_legacy(
  p_wp_shop_id bigint,p_shop_slug text,p_payload jsonb,p_actor_label text
) returns uuid language plpgsql security definer set search_path=private,pg_temp as $$
declare v_id uuid; v_shop private.managed_shops%rowtype;
begin
  if p_wp_shop_id < 1 or p_shop_slug !~ '^[^/[:space:]]{1,200}$' or char_length(trim(p_actor_label)) not between 1 and 120 then
    raise exception 'invalid legacy managed identity' using errcode='22023';
  end if;
  select * into v_shop from private.managed_shops where existing_wp_shop_id=p_wp_shop_id for update;
  if found then
    if v_shop.shop_slug <> p_shop_slug or v_shop.existing_shop_slug <> p_shop_slug then
      raise exception 'legacy shop identity mismatch' using errcode='23000';
    end if;
    return v_shop.id;
  end if;
  if exists (select 1 from private.managed_shops where shop_slug=p_shop_slug) then
    raise exception 'managed shop slug already exists' using errcode='23000';
  end if;
  insert into private.managed_shops(existing_wp_shop_id,existing_shop_slug,shop_slug,current_revision)
  values(p_wp_shop_id,p_shop_slug,p_shop_slug,1) returning id into v_id;
  perform private.insert_managed_shop_revision(v_id,1,'draft',p_payload);
  return v_id;
end;
$$;

create or replace function private.create_managed_shop(
  p_shop_slug text,p_payload jsonb,p_actor_label text
) returns uuid language plpgsql security definer set search_path=private,pg_temp as $$
declare v_id uuid;
begin
  if p_shop_slug !~ '^[a-z0-9][a-z0-9-]{1,118}[a-z0-9]$' or char_length(trim(p_actor_label)) not between 1 and 120 then
    raise exception 'invalid new managed shop identity' using errcode='22023';
  end if;
  insert into private.managed_shops(shop_slug,current_revision) values(p_shop_slug,1) returning id into v_id;
  perform private.insert_managed_shop_revision(v_id,1,'draft',p_payload);
  return v_id;
end;
$$;

create or replace function private.attach_managed_shop_asset(
  p_managed_shop_id uuid,p_asset_id uuid,p_object_key text,p_sha256 text,p_content_type text,p_byte_size integer,p_width integer,p_height integer,p_actor_label text
) returns uuid language plpgsql security definer set search_path=private,pg_temp as $$
declare v_state text; v_extension text;
begin
  select r.state into v_state from private.managed_shops s
  join private.managed_shop_revisions r on r.managed_shop_id=s.id and r.revision=s.current_revision
  where s.id=p_managed_shop_id for update;
  if not found or v_state not in ('draft','changes_requested') then raise exception 'managed shop asset unavailable' using errcode='42501'; end if;
  v_extension := case p_content_type when 'image/png' then 'png' when 'image/jpeg' then 'jpg' when 'image/webp' then 'webp' else null end;
  if p_asset_id is null or p_object_key <> format('managed-shops/%s/%s.%s',p_managed_shop_id,p_asset_id,v_extension)
    or p_sha256 !~ '^[0-9a-f]{64}$' or p_byte_size not between 1 and 5242880 or p_width not between 1 and 8000 or p_height not between 1 and 8000
    or char_length(trim(p_actor_label)) not between 1 and 120 then
    raise exception 'managed shop asset rejected' using errcode='42501';
  end if;
  insert into private.managed_shop_assets(id,managed_shop_id,object_key,sha256,content_type,byte_size,width,height)
  values(p_asset_id,p_managed_shop_id,p_object_key,p_sha256,p_content_type,p_byte_size,p_width,p_height);
  return p_asset_id;
end;
$$;

create or replace function private.save_managed_shop_draft(
  p_managed_shop_id uuid,p_expected_revision integer,p_payload jsonb,p_actor_label text
) returns text language plpgsql security definer set search_path=private,pg_temp as $$
declare v_shop private.managed_shops%rowtype; v_state text; v_next integer;
begin
  select * into v_shop from private.managed_shops where id=p_managed_shop_id for update;
  if not found then return 'not_found'; end if;
  if v_shop.current_revision <> p_expected_revision then return 'conflict'; end if;
  select state into v_state from private.managed_shop_revisions where managed_shop_id=v_shop.id and revision=v_shop.current_revision for key share;
  if v_state not in ('draft','changes_requested','approved') then return 'conflict'; end if;
  v_next := v_shop.current_revision + 1;
  perform private.insert_managed_shop_revision(v_shop.id,v_next,'draft',p_payload);
  update private.managed_shops set current_revision=v_next,updated_at=now() where id=v_shop.id;
  return 'ok';
end;
$$;

create or replace function private.submit_managed_shop_revision(
  p_managed_shop_id uuid,p_expected_revision integer,p_actor_label text
) returns text language plpgsql security definer set search_path=private,pg_temp as $$
declare v_shop private.managed_shops%rowtype;
begin
  if char_length(trim(p_actor_label)) not between 1 and 120 then raise exception 'invalid actor' using errcode='22023'; end if;
  select * into v_shop from private.managed_shops where id=p_managed_shop_id for update;
  if not found or v_shop.current_revision <> p_expected_revision then return 'conflict'; end if;
  update private.managed_shop_revisions set state='submitted',submitted_at=now()
  where managed_shop_id=v_shop.id and revision=v_shop.current_revision and state='draft';
  if not found then return 'conflict'; end if;
  insert into private.managed_shop_reviews(managed_shop_id,revision,decision,reviewer_label) values(v_shop.id,v_shop.current_revision,'submitted',trim(p_actor_label));
  return 'ok';
end;
$$;

create or replace function private.review_managed_shop_revision(
  p_managed_shop_id uuid,p_expected_revision integer,p_decision text,p_reviewer_label text,p_note text default null
) returns text language plpgsql security definer set search_path=private,pg_temp as $$
declare v_shop private.managed_shops%rowtype; v_revision private.managed_shop_revisions%rowtype;
begin
  if p_decision not in ('changes_requested','approved') or char_length(trim(p_reviewer_label)) not between 1 and 120
    or char_length(trim(coalesce(p_note,''))) > 5000 or (p_decision='changes_requested' and nullif(trim(coalesce(p_note,'')),'') is null) then
    raise exception 'invalid managed shop review' using errcode='22023';
  end if;
  select * into v_shop from private.managed_shops where id=p_managed_shop_id for update;
  if not found or v_shop.current_revision <> p_expected_revision then return 'conflict'; end if;
  select * into v_revision from private.managed_shop_revisions where managed_shop_id=v_shop.id and revision=v_shop.current_revision for update;
  if not found or v_revision.state <> 'submitted' then return 'conflict'; end if;
  update private.managed_shop_revisions set state=p_decision where managed_shop_id=v_shop.id and revision=v_shop.current_revision;
  insert into private.managed_shop_reviews(managed_shop_id,revision,decision,reviewer_label,note)
  values(v_shop.id,v_shop.current_revision,p_decision,trim(p_reviewer_label),nullif(trim(coalesce(p_note,'')),''));
  if p_decision='approved' then
    insert into private.managed_shop_publications(
      managed_shop_id,approved_revision,shop_slug,canonical_url,directory_id,existing_wp_shop_id,shop_name,area_slug,area_name,official_url,introduction,address,business_hours,phone,line_url,booking_url,basic_price,price_90,banner_asset_id,gallery_asset_ids
    ) values (
      v_shop.id,v_revision.revision,v_shop.shop_slug,v_shop.canonical_url,v_shop.directory_id,v_shop.existing_wp_shop_id,
      v_revision.shop_name,v_revision.area_slug,v_revision.area_name,v_revision.official_url,v_revision.introduction,v_revision.address,v_revision.business_hours,v_revision.phone,v_revision.line_url,v_revision.booking_url,v_revision.basic_price,v_revision.price_90,v_revision.banner_asset_id,v_revision.gallery_asset_ids
    ) on conflict(managed_shop_id) do update set
      approved_revision=excluded.approved_revision,shop_slug=excluded.shop_slug,canonical_url=excluded.canonical_url,directory_id=excluded.directory_id,existing_wp_shop_id=excluded.existing_wp_shop_id,
      shop_name=excluded.shop_name,area_slug=excluded.area_slug,area_name=excluded.area_name,official_url=excluded.official_url,introduction=excluded.introduction,address=excluded.address,business_hours=excluded.business_hours,phone=excluded.phone,line_url=excluded.line_url,booking_url=excluded.booking_url,basic_price=excluded.basic_price,price_90=excluded.price_90,banner_asset_id=excluded.banner_asset_id,gallery_asset_ids=excluded.gallery_asset_ids,published_at=now();
  end if;
  update private.managed_shops set updated_at=now() where id=v_shop.id;
  return 'ok';
end;
$$;

create or replace function api.get_operator_managed_shop_page(p_query text default '',p_page integer default 1,p_page_size integer default 30)
returns jsonb language sql security invoker set search_path=private,pg_temp as $$
  select jsonb_build_object(
    'total',count(*),
    'records',coalesce(jsonb_agg(jsonb_build_object(
      'id',id,'directory_id',directory_id,'existing_wp_shop_id',existing_wp_shop_id,'shop_slug',shop_slug,'canonical_url',canonical_url,'current_revision',current_revision,'current_state',current_state,'published_revision',published_revision
    ) order by shop_slug),'[]'::jsonb)
  ) from (
    select s.id,s.directory_id,s.existing_wp_shop_id,s.shop_slug,s.canonical_url,s.current_revision,r.state as current_state,p.approved_revision as published_revision
    from private.managed_shops s join private.managed_shop_revisions r on r.managed_shop_id=s.id and r.revision=s.current_revision
    left join private.managed_shop_publications p on p.managed_shop_id=s.id
    where s.shop_slug ilike '%' || left(coalesce(p_query,''),120) || '%'
    order by s.shop_slug offset greatest(p_page-1,0)*least(greatest(p_page_size,1),100) limit least(greatest(p_page_size,1),100)
  ) page
$$;

create or replace function api.get_operator_managed_shop_detail(p_managed_shop_id uuid)
returns jsonb language sql security invoker set search_path=private,pg_temp as $$
  select jsonb_build_object(
    'shop',to_jsonb(s),'current_revision',to_jsonb(r),'publication',to_jsonb(p),
    'assets',coalesce((select jsonb_agg(to_jsonb(a) order by a.created_at) from private.managed_shop_assets a where a.managed_shop_id=s.id),'[]'::jsonb),
    'reviews',coalesce((select jsonb_agg(to_jsonb(q) order by q.created_at desc) from private.managed_shop_reviews q where q.managed_shop_id=s.id),'[]'::jsonb)
  ) from private.managed_shops s join private.managed_shop_revisions r on r.managed_shop_id=s.id and r.revision=s.current_revision
  left join private.managed_shop_publications p on p.managed_shop_id=s.id where s.id=p_managed_shop_id
$$;

