-- Generalized operator-managed shop directory. WordPress remains a read-only
-- legacy identity source; this schema never writes WordPress records.
create table private.managed_shops (
  id uuid primary key default gen_random_uuid(),
  directory_id bigint generated by default as identity (start with 1000000000) unique not null,
  existing_wp_shop_id bigint unique,
  existing_shop_slug text,
  shop_slug text not null unique check (shop_slug ~ '^[^/[:space:]]{1,200}$'),
  canonical_url text generated always as ('https://mens-esthe-kuchikomi.com/shops/' || shop_slug || '/') stored,
  current_revision integer not null default 0 check (current_revision >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((existing_wp_shop_id is null and existing_shop_slug is null) or (existing_wp_shop_id is not null and existing_shop_slug is not null)),
  check (existing_shop_slug is null or existing_shop_slug = shop_slug)
);

create table private.managed_shop_revisions (
  managed_shop_id uuid not null references private.managed_shops(id) on delete restrict,
  revision integer not null check (revision > 0),
  state text not null check (state in ('draft','submitted','changes_requested','approved')),
  shop_name text not null check (char_length(shop_name) between 1 and 120),
  area_slug text not null check (area_slug ~ '^[^/[:space:]]{1,200}$'),
  area_name text not null check (char_length(area_name) between 1 and 120),
  official_url text not null check (official_url ~ '^https?://'),
  introduction text check (introduction is null or char_length(introduction) <= 5000),
  address text check (address is null or char_length(address) <= 500),
  business_hours text check (business_hours is null or char_length(business_hours) <= 500),
  phone text check (phone is null or char_length(phone) <= 120),
  line_url text check (line_url is null or line_url ~ '^https?://'),
  booking_url text check (booking_url is null or booking_url ~ '^https?://'),
  basic_price integer check (basic_price is null or basic_price between 1 and 10000000),
  price_90 integer check (price_90 is null or price_90 between 1 and 10000000),
  banner_asset_id uuid,
  gallery_asset_ids uuid[] not null default '{}'::uuid[] check (cardinality(gallery_asset_ids) <= 10),
  created_at timestamptz not null default now(),
  submitted_at timestamptz,
  primary key (managed_shop_id, revision),
  check ((state = 'submitted' and submitted_at is not null) or (state <> 'submitted'))
);

create table private.managed_shop_assets (
  id uuid primary key,
  managed_shop_id uuid not null references private.managed_shops(id) on delete restrict,
  object_key text not null unique check (object_key ~ '^managed-shops/[0-9a-f-]+/[0-9a-f-]+[.](png|jpe?g|webp)$'),
  sha256 text not null check (sha256 ~ '^[0-9a-f]{64}$'),
  content_type text not null check (content_type in ('image/png','image/jpeg','image/webp')),
  byte_size integer not null check (byte_size between 1 and 5242880),
  width integer not null check (width between 1 and 8000),
  height integer not null check (height between 1 and 8000),
  created_at timestamptz not null default now()
);

alter table private.managed_shop_revisions
  add constraint managed_shop_revisions_banner_asset_fk
  foreign key (banner_asset_id) references private.managed_shop_assets(id) on delete restrict;

create table private.managed_shop_reviews (
  id uuid primary key default gen_random_uuid(),
  managed_shop_id uuid not null,
  revision integer not null,
  decision text not null check (decision in ('submitted','changes_requested','approved')),
  reviewer_label text not null check (char_length(reviewer_label) between 1 and 120),
  note text check (note is null or char_length(note) <= 5000),
  created_at timestamptz not null default now(),
  foreign key (managed_shop_id, revision) references private.managed_shop_revisions(managed_shop_id, revision) on delete restrict
);

create table private.managed_shop_publications (
  managed_shop_id uuid primary key references private.managed_shops(id) on delete restrict,
  approved_revision integer not null,
  shop_slug text not null unique,
  canonical_url text not null,
  directory_id bigint not null unique,
  existing_wp_shop_id bigint,
  shop_name text not null,
  area_slug text not null,
  area_name text not null,
  official_url text not null,
  introduction text,
  address text,
  business_hours text,
  phone text,
  line_url text,
  booking_url text,
  basic_price integer,
  price_90 integer,
  banner_asset_id uuid references private.managed_shop_assets(id) on delete restrict,
  gallery_asset_ids uuid[] not null default '{}'::uuid[],
  published_at timestamptz not null default now(),
  foreign key (managed_shop_id, approved_revision) references private.managed_shop_revisions(managed_shop_id, revision) on delete restrict
);

create index managed_shops_legacy_identity_idx on private.managed_shops(existing_wp_shop_id) where existing_wp_shop_id is not null;
create index managed_shop_revisions_current_idx on private.managed_shop_revisions(managed_shop_id, revision desc);
create index managed_shop_publications_area_idx on private.managed_shop_publications(area_slug, shop_name);

